import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

enum AppLanguage { english, urdu, punjabi }

class LanguageService extends ChangeNotifier {
  AppLanguage _currentLanguage = AppLanguage.english;

  AppLanguage get currentLanguage => _currentLanguage;

  Future<void> init() async {
    final prefs = await SharedPreferences.getInstance();
    final String? langCode = prefs.getString('app_language');
    if (langCode != null) {
      _currentLanguage = AppLanguage.values.firstWhere(
        (e) => e.name == langCode,
        orElse: () => AppLanguage.english,
      );
      notifyListeners();
    }
  }

  Locale get currentLocale {
    switch (_currentLanguage) {
      case AppLanguage.urdu:
        return const Locale('ur', 'PK');
      case AppLanguage.punjabi:
        return const Locale('pa', 'PK');
      default:
        return const Locale('en', 'US');
    }
  }

  /// Returns the locale string specifically for date formatting.
  /// For Punjabi, we return 'ur_PK' to force Shahmukhi (Arabic) script 
  /// instead of the default Gurmukhi script.
  String get dateLocale {
    if (_currentLanguage == AppLanguage.punjabi) return 'ur_PK';
    if (_currentLanguage == AppLanguage.urdu) return 'ur_PK';
    return 'en_US';
  }

  void setLanguage(AppLanguage language) async {
    _currentLanguage = language;
    notifyListeners();
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('app_language', language.name);
  }

  String translate(String key) {
    if (_translations[_currentLanguage] != null && _translations[_currentLanguage]![key] != null) {
      return _translations[_currentLanguage]![key]!;
    }
    return _translations[AppLanguage.english]?[key] ?? key;
  }

